//! Build script: compiles the vendored libwebp 1.6.0 (encoder + decoder + SharpYUV) and the C shim
//! `src/webp_shim.c` into the crate when the `webp` feature is on.
//!
//! SIMD follows the target, mirroring how the rest of the native code is built:
//! - `aarch64`: NEON is baseline, so the NEON sources are always built.
//! - `arm` (armv7): NEON sources are built only when the Rust target has the `neon` feature
//!   (`thumbv7neon-linux-androideabi`); the plain `armv7-linux-androideabi` build stays NEON-free.
//!   The Kotlin loader picks the right library at run time.
//!
//! Only the Android ARM targets are supported; x86 SIMD sources are not built (a host build, used
//! for `cargo test`, simply runs libwebp's scalar code).

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo::rustc-check-cfg=cfg(ssiv_check)");
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=src/webp_shim.c");
    println!("cargo::rerun-if-changed=vendor/libwebp");
    if env::var_os("CARGO_FEATURE_WEBP").is_some() {
        build_webp();
    }
}

fn build_webp() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join("vendor/libwebp");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let features = env::var("CARGO_CFG_TARGET_FEATURE").unwrap_or_default();
    let has_feature = |name: &str| features.split(',').any(|f| f == name);

    let aarch64 = arch == "aarch64";
    let arm_neon = arch == "arm" && has_feature("neon");
    let neon = aarch64 || arm_neon;
    let threads =
        env::var("CARGO_CFG_TARGET_FAMILY").is_ok_and(|f| f.split(',').any(|x| x == "unix"));

    // libwebp is built with HAVE_CONFIG_H so the *_HAVE_* macros below (not the compiler defaults)
    // decide which run-time dispatch paths exist.
    let cfg_dir = out.join("webp_cfg");
    let cfg_file = cfg_dir.join("src/webp/config.h");
    fs::create_dir_all(cfg_file.parent().unwrap()).unwrap();
    let mut config = String::from("/* generated by build.rs */\n");
    if threads {
        config.push_str("#define WEBP_USE_THREAD 1\n");
    }
    if neon {
        config.push_str("#define WEBP_HAVE_NEON 1\n");
    }
    fs::write(&cfg_file, config).unwrap();

    let mut base: Vec<PathBuf> = Vec::new();
    for dir in ["src/dec", "src/dsp", "src/enc", "src/utils", "sharpyuv"] {
        let mut files: Vec<PathBuf> = fs::read_dir(root.join(dir))
            .unwrap_or_else(|e| panic!("missing vendored libwebp dir {dir}: {e}"))
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.extension().is_some_and(|x| x == "c"))
            .collect();
        files.sort();
        for file in files {
            let name = file.file_name().unwrap().to_string_lossy().into_owned();
            let stem = name.trim_end_matches(".c");
            let x86_only =
                stem.ends_with("_sse2") || stem.ends_with("_sse41") || stem.ends_with("_avx2");
            if x86_only || (stem.ends_with("_neon") && !neon) {
                continue;
            }
            base.push(file);
        }
    }
    base.push(manifest.join("src/webp_shim.c"));

    let mut build = cc::Build::new();
    build
        .include(&root)
        .include(&cfg_dir)
        .define("HAVE_CONFIG_H", None)
        .define("NDEBUG", None)
        .opt_level(3)
        .warnings(false)
        .flag_if_supported("-fvisibility=hidden")
        .flag_if_supported("-ffunction-sections")
        .flag_if_supported("-fdata-sections");
    if arm_neon {
        build.flag("-mfpu=neon");
    }
    for file in &base {
        build.file(file);
    }
    build.compile("ssiv_webp_base");
}
